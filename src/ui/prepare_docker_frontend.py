"""Stage the maintained src/ui frontend at the path expected by Dockerfile."""

import argparse
import json
import os
import shutil
import tempfile
from pathlib import Path


MARKER_NAME = ".honest-filing-ui-generated"
MARKER_CONTENT = "Generated from src/ui/prepare_docker_frontend.py; do not edit."
PDFJS_ASSETS = {
    "build": ("pdf.mjs", "pdf.worker.mjs"),
    "cmaps": None,
    "standard_fonts": None,
    "wasm": None,
}


def parse_args() -> argparse.Namespace:
    repository_root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(
        description=(
            "Copy src/ui and its local PDF.js runtime assets into the frontend/ "
            "directory required by the existing Dockerfile."
        )
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=repository_root / "frontend",
        help="Output directory (default: repository-root/frontend).",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove only a staging directory previously generated by this helper.",
    )
    return parser.parse_args()


def ignore_source_only(_directory: str, names: list[str]) -> set[str]:
    excluded = {"node_modules", "test-fixtures", "package.json", "package-lock.json", ".gitignore", "__pycache__"}
    return {
        name
        for name in names
        if name in excluded or name.endswith((".py", ".pyc"))
    }


def verify_replaceable_output(output_dir: Path) -> None:
    if not output_dir.exists() and not output_dir.is_symlink():
        return
    if output_dir.is_symlink() or not output_dir.is_dir():
        raise RuntimeError(f"Refusing to replace non-directory or symlink output: {output_dir}")

    marker = output_dir / MARKER_NAME
    if not marker.is_file() or marker.read_text(encoding="utf-8") != MARKER_CONTENT:
        raise RuntimeError(
            f"Refusing to overwrite existing frontend directory without this tool's marker: {output_dir}"
        )


def clean_generated_output(output_dir: Path) -> None:
    if not output_dir.exists() and not output_dir.is_symlink():
        print(f"No staged frontend to clean: {output_dir}")
        return
    verify_replaceable_output(output_dir)
    shutil.rmtree(output_dir)
    print(f"Removed generated frontend staging directory: {output_dir}")


def copy_pdfjs_assets(source_package: Path, destination_package: Path) -> None:
    package_manifest = source_package / "package.json"
    if not package_manifest.is_file():
        raise RuntimeError(
            "PDF.js is not installed. Run `npm install --prefix src/ui` before staging the frontend."
        )
    expected_version = json.loads(package_manifest.read_text(encoding="utf-8"))["version"]
    declared_version = json.loads(
        (Path(__file__).parent / "package.json").read_text(encoding="utf-8")
    )["dependencies"]["pdfjs-dist"]
    if expected_version != declared_version:
        raise RuntimeError(
            f"Installed pdfjs-dist version {expected_version} does not match the pinned "
            f"version {declared_version}; run `npm ci --prefix src/ui`."
        )

    for asset_directory, filenames in PDFJS_ASSETS.items():
        source = source_package / asset_directory
        destination = destination_package / asset_directory
        if filenames is None:
            if not source.is_dir():
                raise RuntimeError(f"Required PDF.js asset directory is missing: {source}")
            shutil.copytree(source, destination)
            continue

        destination.mkdir(parents=True, exist_ok=True)
        for filename in filenames:
            source_file = source / filename
            if not source_file.is_file():
                raise RuntimeError(f"Required PDF.js runtime file is missing: {source_file}")
            shutil.copy2(source_file, destination / filename)


def stage_frontend(output_dir: Path) -> None:
    ui_dir = Path(__file__).resolve().parent
    repository_root = ui_dir.parents[1]
    output_dir = output_dir.expanduser().absolute()
    if output_dir == repository_root or output_dir == ui_dir or ui_dir in output_dir.parents:
        raise RuntimeError(f"Output directory cannot replace or be inside the repository source: {output_dir}")
    verify_replaceable_output(output_dir)

    output_dir.parent.mkdir(parents=True, exist_ok=True)
    stage_dir = Path(tempfile.mkdtemp(prefix=f".{output_dir.name}.staging-", dir=output_dir.parent))
    try:
        shutil.copytree(ui_dir, stage_dir, ignore=ignore_source_only, dirs_exist_ok=True)

        source_package = ui_dir / "node_modules" / "pdfjs-dist"
        destination_package = stage_dir / "node_modules" / "pdfjs-dist"
        copy_pdfjs_assets(source_package, destination_package)
        (stage_dir / MARKER_NAME).write_text(MARKER_CONTENT, encoding="utf-8")

        required_files = (
            stage_dir / "index.html",
            stage_dir / "app.js",
            stage_dir / "pdf_viewer.js",
            destination_package / "build" / "pdf.mjs",
            destination_package / "build" / "pdf.worker.mjs",
        )
        missing = [str(path) for path in required_files if not path.is_file()]
        if missing:
            raise RuntimeError(f"Staged frontend is incomplete; missing: {', '.join(missing)}")

        version = json.loads((source_package / "package.json").read_text(encoding="utf-8"))["version"]
        if output_dir.exists():
            verify_replaceable_output(output_dir)
            shutil.rmtree(output_dir)
        os.replace(stage_dir, output_dir)
    except Exception:
        if stage_dir.exists():
            shutil.rmtree(stage_dir)
        raise

    print(f"Staged src/ui for Docker at: {output_dir}")
    print(f"Included local PDF.js {version} browser runtime and font/CMap/WASM assets.")
    print("Docker Compose can now build from the existing frontend/ path.")


def main() -> int:
    args = parse_args()
    try:
        if args.clean:
            clean_generated_output(args.output.expanduser().absolute())
        else:
            stage_frontend(args.output)
    except (OSError, RuntimeError, KeyError, json.JSONDecodeError) as error:
        raise SystemExit(f"Frontend staging failed: {error}") from error
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
